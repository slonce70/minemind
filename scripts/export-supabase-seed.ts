import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { validateQuestionBank } from '../src/features/content/content-validator';
import { contentDifficulties, contentLocales, type ContentQuestionBank } from '../src/features/content/types';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const questionBankPath = path.join(repoRoot, 'content/minecraft/minecraft-question-bank.v1.json');
export const seedPath = path.join(repoRoot, 'supabase/seed.sql');

function sqlText(value: string) {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Idempotent seed: packs and questions are upserted by slug / content id, never deleted. */
export function buildSeedSql(bank: ContentQuestionBank) {
  const statements = [
    '-- Generated by scripts/export-supabase-seed.ts from content/minecraft/minecraft-question-bank.v1.json.\n' +
      '-- Do not edit by hand: change the master bank, then run `npm run export:content`.',
    "insert into public.quiz_categories (slug, title)\nvalues ('minecraft', 'MineMind Fan Quiz')\non conflict (slug) do nothing;",
  ];

  for (const locale of contentLocales) {
    for (const difficulty of contentDifficulties) {
      const slug = `minecraft-${locale}-${difficulty}`;
      const records = bank.filter((record) => record.difficulty === difficulty);
      const rows = records.map((record, index) =>
        [
          sqlText(record.id),
          sqlText(record.prompt[locale]),
          ...record.options.map((option) => sqlText(option[locale])),
          record.correctIndex,
          sqlText(record.explanation[locale]),
          index + 1,
          record.isActive,
        ].join(', ')
      );

      statements.push(
        `insert into public.question_packs (category_id, locale, age_band, difficulty, title, slug, is_active)
select id, '${locale}', '8-12', '${difficulty}', 'MineMind ${locale} ${difficulty}', '${slug}', true
from public.quiz_categories
where slug = 'minecraft'
on conflict (slug) do update set is_active = true, title = excluded.title;`,
        `insert into public.questions (pack_id, content_id, prompt, option_a, option_b, option_c, option_d, correct_option, explanation, sort_order, is_active)
select pack.id, v.content_id, v.prompt, v.option_a, v.option_b, v.option_c, v.option_d, v.correct_option, v.explanation, v.sort_order, v.is_active
from public.question_packs pack
cross join (values
  (${rows.join('),\n  (')})
) as v(content_id, prompt, option_a, option_b, option_c, option_d, correct_option, explanation, sort_order, is_active)
where pack.slug = '${slug}'
on conflict (pack_id, content_id) do update set
  prompt = excluded.prompt,
  option_a = excluded.option_a,
  option_b = excluded.option_b,
  option_c = excluded.option_c,
  option_d = excluded.option_d,
  correct_option = excluded.correct_option,
  explanation = excluded.explanation,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active;`
      );
    }
  }

  return `${statements.join('\n\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bank = validateQuestionBank(JSON.parse(readFileSync(questionBankPath, 'utf8')));
  writeFileSync(seedPath, buildSeedSql(bank), 'utf8');
  console.log(`Wrote ${path.relative(repoRoot, seedPath)} for ${bank.length} question record(s).`);
}
