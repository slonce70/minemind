const outline = '#24170F';
const eyes = { b: '#1B1B22', w: '#FFFFFF' };

type AvatarPreset = {
  color: string;
  id: string;
  label: string;
  labelKey: string;
  sprite: PixelSpriteData;
};

function avatar(id: string, label: string, color: string, palette: Record<string, string>, rows: string[]): AvatarPreset {
  return { color, id, label, labelKey: `avatars.${id}`, sprite: { palette: { k: outline, ...eyes, ...palette }, rows } };
}

