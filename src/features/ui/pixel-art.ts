/**
 * Pixel art drawn as rows of characters: each character is a palette key, '.' is transparent.
 * All sprites in the app are original and live in code (see assets/LICENSES.md).
 */
export type PixelSpriteData = {
  palette: Record<string, string>;
  rows: readonly string[];
};

export type SpriteRun = { color: string; opacity?: number; width: number; x: number; y: number };

/** Merges horizontal runs of one colour into a single rect to keep the SVG small. */
export function spriteRuns(sprite: PixelSpriteData, opacities: Record<string, number> = {}): SpriteRun[] {
  const runs: SpriteRun[] = [];

  sprite.rows.forEach((row, y) => {
    let x = 0;

    while (x < row.length) {
      const key = row[x];
      let width = 1;

      while (row[x + width] === key) {
        width += 1;
      }

      if (key !== '.' && sprite.palette[key]) {
        runs.push({ color: sprite.palette[key], opacity: opacities[key], width, x, y });
      }

      x += width;
    }
  });

  return runs;
}

