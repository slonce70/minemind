// Kubik, the MineMind mascot: an amber lantern-cube with a sprout. Original pixel art.
export type MascotMood = 'happy' | 'wow' | 'sad';

const face: Record<MascotMood, [string, string, string, string]> = {
  happy: ['owwoooowwo', 'owboooowbo', 'pokooookop', 'oookkkkooo'],
  sad: ['oooooooooo', 'obboooobbo', 'poookkooop', 'oookookooo'],
  wow: ['owwoooowwo', 'owboooowbo', 'poookkooop', 'poookkooop'],
};

function buildMascotSprite(mood: MascotMood): PixelSpriteData {
  const [eyesTop, eyesBottom, mouthTop, mouthBottom] = face[mood];

  return {
    palette: {
      G: '#3F8F3A',
      b: '#2A1A10',
      d: '#C9772E',
      g: '#7BD35F',
      k: '#2A1A10',
      o: '#F2A541',
      p: '#FF8A7A',
      w: '#FFFFFF',
      y: '#FFD27A',
    },
    rows: [
      '.......gg.......',
      '.....ggGg.gg....',
      '......gGgGGg....',
      '.......kGk......',
      '..kkkkkkkkkkkk..',
      '.kyyyyyyyyyyyyk.',
      `.ky${'o'.repeat(10)}dk.`,
      `.ky${eyesTop}dk.`,
      `.ky${eyesBottom}dk.`,
      `.ky${'o'.repeat(10)}dk.`,
      `.ky${mouthTop}dk.`,
      `.ky${mouthBottom}dk.`,
      `.k${'d'.repeat(12)}k.`,
      '..kkkkkkkkkkkk..',
      '...kdk....kdk...',
      '...kk......kk...',
    ],
  };
}

export const mascotSprites: Record<MascotMood, PixelSpriteData> = {
  happy: buildMascotSprite('happy'),
  sad: buildMascotSprite('sad'),
  wow: buildMascotSprite('wow'),
};
